-- GymFlow: modelo objetivo de coordinación 1.0, 2026-11-03.
-- Solo para una base VACIA. No es una migración de la base publicada.
-- No contiene seed, contraseñas, DROP ni reinicios de datos.
BEGIN;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (length(btrim(name)) > 0),
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'PROFESSOR', 'MEMBER')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT users_email_normalized CHECK (email = lower(btrim(email)))
);

CREATE TABLE activities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    description VARCHAR(1000),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX activities_name_unique ON activities (lower(btrim(name)));

CREATE TABLE classes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id INTEGER NOT NULL REFERENCES activities(id) ON DELETE RESTRICT,
    professor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    cancelled BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT classes_valid_time CHECK (ends_at > starts_at),
    CONSTRAINT classes_unique_schedule UNIQUE (activity_id, professor_id, starts_at)
);
CREATE INDEX classes_starts_at_idx ON classes (starts_at);
CREATE INDEX classes_professor_idx ON classes (professor_id, starts_at);

CREATE TABLE package_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    class_credits INTEGER NOT NULL CHECK (class_credits > 0),
    duration_days INTEGER NOT NULL CHECK (duration_days > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX package_types_name_unique ON package_types (lower(btrim(name)));

CREATE TABLE member_packages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    package_type_id INTEGER NOT NULL REFERENCES package_types(id) ON DELETE RESTRICT,
    starts_on DATE NOT NULL,
    expires_on DATE NOT NULL,
    initial_credits INTEGER NOT NULL CHECK (initial_credits > 0),
    remaining_credits INTEGER NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT member_packages_credit_bounds
        CHECK (remaining_credits BETWEEN 0 AND initial_credits),
    CONSTRAINT member_packages_valid_dates CHECK (expires_on >= starts_on),
    CONSTRAINT member_packages_unique_assignment
        UNIQUE (member_id, package_type_id, starts_on),
    CONSTRAINT member_packages_id_member_unique UNIQUE (id, member_id)
);
CREATE INDEX member_packages_selection_idx
    ON member_packages (member_id, expires_on, assigned_at, id);

CREATE TABLE class_reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    member_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    member_package_id INTEGER NOT NULL,
    cancelled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    credit_refunded BOOLEAN NOT NULL DEFAULT FALSE,
    attendance_status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
        CHECK (attendance_status IN ('PENDING', 'PRESENT', 'ABSENT')),
    attendance_recorded_by INTEGER REFERENCES users(id) ON DELETE RESTRICT,
    attendance_recorded_at TIMESTAMPTZ,
    CONSTRAINT reservation_package_owner
        FOREIGN KEY (member_package_id, member_id)
        REFERENCES member_packages(id, member_id) ON DELETE RESTRICT,
    CONSTRAINT reservation_cancellation_time
        CHECK ((cancelled AND cancelled_at IS NOT NULL)
            OR (NOT cancelled AND cancelled_at IS NULL)),
    CONSTRAINT reservation_refund_requires_cancel CHECK (NOT credit_refunded OR cancelled),
    CONSTRAINT reservation_attendance_audit
        CHECK ((attendance_status = 'PENDING'
                    AND attendance_recorded_by IS NULL
                    AND attendance_recorded_at IS NULL)
            OR (attendance_status IN ('PRESENT', 'ABSENT')
                    AND attendance_recorded_by IS NOT NULL
                    AND attendance_recorded_at IS NOT NULL))
);
-- La unicidad es por SOCIO, no por paquete. Las canceladas conservan historial.
CREATE UNIQUE INDEX reservations_one_active_per_member_class
    ON class_reservations (class_id, member_id) WHERE cancelled = FALSE;
CREATE INDEX reservations_member_idx ON class_reservations (member_id, created_at);
CREATE INDEX reservations_package_idx ON class_reservations (member_package_id);

COMMIT;

